import React from 'react';
import { createRoot } from 'react-dom/client';
import { App } from './App';
import { FloatingView } from './FloatingView';
import { applyStoredTheme } from './theme';
import './styles.css';
import {installRendererLogging,rendererError} from './logging';
import {NoticeHost,noticeAPI} from './Notices';
installRendererLogging();
Object.defineProperty(window,'kmmNotice',{value:noticeAPI,writable:false,configurable:false});
applyStoredTheme();
createRoot(document.getElementById('root')!,{onUncaughtError:(error)=>rendererError('react-error',error,'react.uncaught'),onCaughtError:(error)=>rendererError('react-error',error,'react.caught'),onRecoverableError:(error)=>rendererError('react-error',error,'react.recoverable')}).render(<React.StrictMode>{location.hash==='#floating'?<FloatingView/>:<div className="main-window"><div className="window-titlebar" aria-hidden="true"/><App /></div>}<NoticeHost/></React.StrictMode>);
