import { contextBridge, ipcRenderer } from 'electron';
import type { DesktopAPI } from '../shared/contracts';
import type {IPCChannel,IPCArguments,IPCContracts} from '../shared/ipc-contracts';
const invoke=<C extends IPCChannel>(channel:C,...args:IPCArguments<C>):ReturnType<IPCContracts[C]>=>ipcRenderer.invoke(channel,...args) as ReturnType<IPCContracts[C]>;
const api: DesktopAPI = {
  checkAppUpdate:()=>invoke('update:check'),
  appUpdateStatus:()=>invoke('update:status'),
  downloadAppUpdate:()=>invoke('update:download'),
  installAppUpdate:()=>invoke('update:install'),
  readSettings: () => invoke('settings:read'),
  saveSettings: settings => invoke('settings:save', settings),
  saveGamePaths:(game,patch)=>invoke('settings:save-game-paths',game,patch),
  saveDesktopPreferences:patch=>invoke('settings:save-desktop-preferences',patch),
  chooseDirectory: current => invoke('directory:choose', current),
  inspect: (game, root) => invoke('xxmi:inspect', game, root),
  deploy: settings => invoke('xxmi:deploy', settings),
  deploymentProgress: () => invoke('deployment:progress'),
  syncPaths: settings => invoke('xxmi:sync', settings),
  checkRuntime: () => invoke('runtime:check'),
  openRuntimeDownload: () => invoke('runtime:download'),
  scanMods: game => invoke('mods:scan',game),
  operateMod: (game,id,operation) => invoke('mods:operate',game,id,operation),
  batchMods:(game,ids,operation,choices)=>invoke('mods:batch',game,ids,operation,choices),
  saveExclusiveGroup:(game,id,name,modIds,enabledId)=>invoke('mods:exclusive-save',game,id,name,modIds,enabledId),
  deleteExclusiveGroup:(game,id)=>invoke('mods:exclusive-delete',game,id),
  openModSource:(game,id)=>invoke('mods:source',game,id),
  importMods: (game,kind) => invoke('mods:import',game,kind),
  replaceMod: (game,id,kind) => invoke('mods:replace',game,id,kind),
  deleteMod: (game,id) => invoke('mods:delete',game,id),
  cover: (game,id) => invoke('mods:cover',game,id),
  characterCovers:game=>invoke('characters:covers',game),
  chooseCharacterCover:(game,name)=>invoke('characters:choose-cover',game,name),
  chooseCover: (game,id) => invoke('mods:choose-cover',game,id),
  addGroup: (game,kind,name) => invoke('mods:group',game,kind,name),
  presets:game=>invoke('presets:list',game),
  savePreset:(game,id,name,members)=>invoke('presets:save',game,id,name,members),
  addModsToPreset:(game,id,modIds)=>invoke('presets:add-members',game,id,modIds),
  deletePreset:(game,id)=>invoke('presets:delete',game,id),
  applyPreset:(game,id,choices)=>invoke('presets:apply',game,id,choices),
  iniFiles:(game,id)=>invoke('ini:list',game,id),
  readIni:(game,id,relativePath)=>invoke('ini:read',game,id,relativePath),
  saveIni:(game,id,relativePath,digest,edit)=>invoke('ini:save',game,id,relativePath,digest,edit),
  conflicts:game=>invoke('conflicts:scan',game),
  recovery:game=>invoke('recovery:list',game),
  createBackup:(game,name)=>invoke('recovery:create',game,name),
  restore:(game,id)=>invoke('recovery:restore',game,id),
  desktopStatus:()=>invoke('desktop:status'),
  floating:visible=>invoke('desktop:floating',visible),
  showMain:()=>invoke('desktop:show'),
  quit:()=>invoke('desktop:quit'),
  selectGame:game=>invoke('desktop:game',game),
  launchXXMI:(game,mode)=>invoke('desktop:launch',game,mode),
  refreshGame:game=>invoke('desktop:refresh',game),
  openLink:(game,kind)=>invoke('desktop:link',game,kind),
  onDesktopChange:callback=>{const listener=(_event:Electron.IpcRendererEvent,value:import('../shared/contracts').DesktopChange)=>callback(value);ipcRenderer.on('desktop:changed',listener);return()=>{ipcRenderer.removeListener('desktop:changed',listener);};},
};
contextBridge.exposeInMainWorld('kmm', api);
